window.MODENA_getMember = function (id) {
  return (window.MODENA_TEAM || []).filter(function (m) { return m.id === id; })[0] || null;
};

/* Portraits de l'équipe : cadre, numéro, qualification existante et cartouche du nom. */
window.MODENA_renderTeamCard = function (m, index) {
  var escape = function (value) {
    return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  };
  var order = typeof index === 'number' ? index : window.MODENA_TEAM.findIndex(function (person) { return person.id === m.id; });
  var number = String(order + 1).padStart(2, '0');
  var credential = /Spécialiste CNB/.test(m.barreau || '') ? 'Spécialiste CNB' : '';
  var focus = (m.expertises || []).slice(0, 3).join(' · ');
  return '<a class="team__member team-profile" href="' + escape(m.id) + '.html" aria-label="Voir le profil de ' + escape(m.name) + '">' +
    '<span class="team-profile__frame">' +
      '<span class="team-profile__meta"><span class="team-profile__number" aria-hidden="true">' + number + '</span><span class="team-profile__credential">' + credential + '</span></span>' +
      '<span class="portrait"><img src="' + escape(m.photo) + '" alt="' + escape(m.name) + '" loading="lazy" width="400" height="500"></span>' +
    '</span>' +
    '<span class="team-profile__caption"><span class="team__name">' + escape(m.name) + '</span><span class="team__role">' + escape(m.role) + '</span></span>' +
    (focus ? '<span class="team__focus">' + escape(focus) + '</span>' : '') +
  '</a>';
};
